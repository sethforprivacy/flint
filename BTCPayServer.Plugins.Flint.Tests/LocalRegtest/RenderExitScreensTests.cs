/// <summary>
/// Writes the unilateral-exit page and the Advanced page's exit-state backup section out as standalone HTML
/// files, so the copy and the layout can be read in a browser without a logged-in BTCPay.
/// </summary>
/// <remarks>
/// <para>
/// <b>This is a developer tool, not a behavioural test.</b> Nothing here asserts what the pages say — the
/// assertions are "the page rendered and the file is not empty", because the artefact is the file. Everything
/// about the exit flow's behaviour is pinned in <see cref="SparkExitPageTests"/> and
/// <see cref="SparkUnilateralExitServiceTests"/>; what those cannot do is show a human what the page looks
/// like, which is the whole reason this file exists.
/// </para>
/// <para>
/// The pages are the real compiled Razor views, executed the way
/// <see cref="SetupTabViewRenderer"/> executes the setup partials: discovered as the
/// <see cref="RazorCompiledItemMetadataAttribute"/> the assemblies carry, instantiated, and run against a real
/// <see cref="ViewContext"/>. What surrounds them is MVC's own machinery rather than a transcription of
/// it — <c>AddMvcCore().AddViews()</c> supplies the production <c>IHtmlGenerator</c> (every <c>asp-for</c>,
/// <c>asp-validation-for</c>, label and form on these pages), the production model metadata, the view buffer
/// scope the tag-helper pipeline writes through, and the production view-component invoker, so the markup in
/// the files is generated by the same code that generates it in BTCPay.
/// </para>
/// <para>
/// <b>What is stood in, and why.</b> There is no HTTP request and no host process, so three things are
/// supplied that a real request would get for free, and each one is named here rather than left to be
/// discovered:
/// </para>
/// <list type="bullet">
/// <item>
/// <description>
/// <b>Routing.</b> <see cref="RoutedUrlHelper"/> composes the plugin's own route shape
/// (<c>/plugins/{storeId}/spark/…</c>) from the action names the views pass their tag helpers. It is not a
/// router and does not pretend to be one: it throws on any action this file has not been told about. Every
/// generated <c>href</c>/<c>action</c> is therefore the URL a real request would have produced, without a
/// route table.
/// </description>
/// </item>
/// <item>
/// <description>
/// <b>Authorisation.</b> <see cref="GrantAllAuthorizationService"/> grants
/// <c>CanModifyStoreSettings</c>, which is the role the pages are written for: the screenshots are meant to
/// show the operator's view, including the signed-hex table the <c>permission</c> attribute guards.
/// </description>
/// </item>
/// <item>
/// <description>
/// <b>Localisation.</b> <see cref="ScreenHostEnvironment"/> is the one fact the localiser plumbing reads off
/// the host. No resource files are found for it, so <c>StringLocalizer</c> returns the English keys the views
/// already carry — which is what a request to an untranslated BTCPay gets.
/// </description>
/// </item>
/// <item>
/// <description>
/// <b>View lookup.</b> <see cref="CompiledViewEngine"/> answers the names a view engine is asked for
/// (<c>_StatusMessage</c>, <c>Components/TitleHeader/Default</c>) out of the compiled views the two assemblies
/// carry, by the identifier the Razor compiler recorded. There is no file system in play, and a name it cannot
/// place fails with the identifiers it tried rather than rendering a blank space.
/// </description>
/// </item>
/// </list>
/// <para>
/// Nothing else is stubbed: <c>vc:title-header</c>, <c>vc:truncate-center</c> and the <c>vc:icon</c> inside
/// the latter go through MVC's own view-component invoker over the real component classes rendering their real
/// <c>Components/*/Default.cshtml</c>, the <c>_StatusMessage</c> partial is core's own compiled view (so a
/// refusal queued in <c>TempData</c> — the "nothing worth exiting" state — renders as the same alert the
/// operator would see), and the tag helpers are MVC's.
/// </para>
/// <para>
/// <b>One class, in the serialised collection.</b> The exit feature is behind a process-wide environment
/// switch and the Advanced page's backup section only renders behind it, so the class joins
/// <see cref="UnilateralExitTestCollection"/> and every test restores the variable in a <c>finally</c>.
/// </para>
/// <para>
/// Run it with <c>dotnet test --filter "FullyQualifiedName~RenderExitScreensTests"</c>; the files land in
/// <see cref="ExitScreenRenderer.OutputDirectory"/> and are inert (they link BTCPay's own stylesheets by
/// absolute URL, so they want the server this repo's checkout already runs).
/// </para>
/// </remarks>
[Collection(UnilateralExitTestCollection.Name)]
public class RenderExitScreensTests
{
